"""Build MELETRA-Installer-Windows.exe with the C# compiler that ships with Windows (no SDK, no Visual Studio).

    python bootstrap/windows/build.py --setup-sha256 <sha> --setup-size <bytes> [--version 3.1.0] [--out dist/MELETRA-Installer-Windows.exe]
    python bootstrap/windows/build.py --test --pins pins.json --out test.exe       a TEST build: loopback http allowed + overrides (never shipped)

The values the program trusts (version, final installer SHA-256 and size, the SHA-256 of every speech-model file) are compiled into Pins.cs, so a changed
manifest can never make the installer accept different bytes.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
CSC = Path(os.environ.get("WINDIR", r"C:\Windows")) / "Microsoft.NET" / "Framework64" / "v4.0.30319" / "csc.exe"
ICON = ROOT / "assets" / "meletra.ico"
SYMBOL = ROOT / "assets" / "meletra-icon-64.png"
MANIFEST_URL = "https://twonezerotwo-hue.github.io/whispermedical-downloads/release-manifest.json"


def assembly_version(version: str) -> str:
    """4.1.0 -> 4.1.0.0 (an assembly version has four numbers; anything that is not numeric becomes 0)."""
    numbers = [part if part.isdigit() else "0" for part in version.split(".")[:4]]
    return ".".join(numbers + ["0"] * (4 - len(numbers)))


def pins_source(version: str, setup_name: str, setup_sha: str, setup_size: int, model: dict, manifest_url: str) -> str:
    rows = "\n".join(f'            case "{name}": return "{info["sha256"]}";' for name, info in sorted(model.items()))
    return f'''// Generated by build.py - the values this installer trusts. Do not edit by hand.
[assembly: System.Reflection.AssemblyTitle("MELETRA Installer")]
[assembly: System.Reflection.AssemblyProduct("MELETRA")]
[assembly: System.Reflection.AssemblyDescription("MELETRA - Medical Learning & Transcription: installer")]
[assembly: System.Reflection.AssemblyCompany("Touche Holding")]
[assembly: System.Reflection.AssemblyVersion("{assembly_version(version)}")]
[assembly: System.Reflection.AssemblyFileVersion("{assembly_version(version)}")]
namespace MELETRA
{{
    static class Pins
    {{
        public const string Version = "{version}";
        public const string ManifestUrl = "{manifest_url}";
        public const string SetupName = "{setup_name}";
        public const string SetupSha256 = "{setup_sha}";
        public const long SetupSize = {setup_size}L;
        public static string ModelSha(string name)
        {{
            switch (name)
            {{
{rows}
                default: return null;
            }}
        }}
    }}
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", default="3.1.0")
    parser.add_argument("--setup-name", default="MELETRA-Setup-Windows-x64.exe")
    parser.add_argument("--setup-sha256")
    parser.add_argument("--setup-size", type=int)
    parser.add_argument("--model-files", type=Path, default=ROOT / "scripts" / "model_files.json")
    parser.add_argument("--pins", type=Path, help="JSON with version/setup_name/setup_sha256/setup_size/model/manifest_url (tests)")
    parser.add_argument("--test", action="store_true")
    parser.add_argument("--out", type=Path, default=ROOT / "dist" / "MELETRA-Installer-Windows.exe")
    args = parser.parse_args()
    if args.pins:
        p = json.loads(args.pins.read_text(encoding="utf-8"))
        source = pins_source(p["version"], p["setup_name"], p["setup_sha256"], p["setup_size"], p["model"], p.get("manifest_url", MANIFEST_URL))
    else:
        if not (args.setup_sha256 and args.setup_size):
            parser.error("--setup-sha256 and --setup-size are required")
        source = pins_source(args.version, args.setup_name, args.setup_sha256.lower(), args.setup_size, json.loads(args.model_files.read_text(encoding="utf-8")), MANIFEST_URL)
    work = args.out.parent / "_build"
    work.mkdir(parents=True, exist_ok=True)
    pins = work / "Pins.cs"
    pins.write_text(source, encoding="utf-8")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    cmd = [str(CSC), "/nologo", "/optimize+", "/target:" + ("exe" if args.test else "winexe"), f"/out:{args.out}", "/platform:anycpu",
           f"/win32icon:{ICON}", f"/resource:{SYMBOL},meletra-symbol.png",
           f"/win32manifest:{HERE / 'app.manifest'}", "/r:System.Web.Extensions.dll", "/r:System.Windows.Forms.dll", "/r:System.Drawing.dll",
           "/r:System.dll", "/r:System.Core.dll"]
    if args.test:
        cmd.append("/define:TESTBUILD")
    cmd += [str(HERE / "MELETRAInstaller.cs"), str(pins)]
    done = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    sys.stdout.buffer.write((done.stdout + done.stderr).encode("utf-8", errors="replace"))                  # the compiler speaks the console's language; never fail on it
    sys.stdout.flush()
    if done.returncode != 0:
        return done.returncode
    print(f"built {args.out} ({args.out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
